#nullable enable
using System.Text.RegularExpressions;
using EtlKit.ControlFlow;
using EtlKit.Primitives;
using Moq;
using Xunit;

namespace EtlKit.Common.Tests;

/// <summary>
/// Database-free snapshot tests for <see cref="CreateTableTask.Sql"/>. The DDL is built from a
/// real connection manager per engine, so the engine's quote characters, type conventions and
/// identity/nullability rules all take part, but nothing is ever opened or executed. They pin the
/// DDL that the per-engine type conventions must keep producing, wherever those conventions live
/// (see docs/tech-debt/TECH-DEBT-DataTypeConverter-Driver-Split.md). Expectations were recorded
/// from the current behavior and reviewed; whitespace is collapsed so only the content is
/// compared.
/// </summary>
public sealed class CreateTableTaskSqlTests
{
    private static string BuildSql(
        ConnectionManagerType engine,
        string tableName,
        List<TableColumn> columns
    )
    {
        // The manager names in TestConnectionManagers match the ConnectionManagerType names.
        using var managerCase = TestConnectionManagers.Get(engine.ToString());
        return BuildSql(managerCase.Manager, tableName, columns);
    }

    private static string BuildSql(
        IConnectionManager manager,
        string tableName,
        List<TableColumn> columns
    )
    {
        var task = new CreateTableTask(tableName, columns) { ConnectionManager = manager };
        return Regex.Replace(task.Sql, @"\s+", " ").Trim();
    }

    // One column per convention that matters: identity primary key, NVARCHAR with and without a
    // length above 255, TEXT, DECIMAL, DATETIME, BIGINT, and a default value. ClickHouse has no
    // identity columns, so its key is a plain column.
    private static List<TableColumn> CustomerColumns(bool identity) =>
        [
            new("Id", "INT", allowNulls: false, isPrimaryKey: true, isIdentity: identity),
            new("Name", "NVARCHAR(100)", allowNulls: false),
            new("Notes", "NVARCHAR(300)", allowNulls: true),
            new("Bio", "TEXT", allowNulls: true),
            new("Amount", "DECIMAL(18,2)", allowNulls: true),
            new("Created", "DATETIME", allowNulls: false),
            new("Counter", "BIGINT", allowNulls: false),
            new("Status", "VARCHAR(10)", allowNulls: false) { DefaultValue = "new" },
        ];

    [Theory]
    [InlineData(
        ConnectionManagerType.SqlServer,
        "CREATE TABLE [Customer] ( [Id] INT IDENTITY(1,1) NOT NULL , [Name] NVARCHAR(100) NOT NULL , [Notes] NVARCHAR(300) NULL , [Bio] VARCHAR(MAX) NULL , [Amount] DECIMAL(18,2) NULL , [Created] DATETIME NOT NULL , [Counter] BIGINT NOT NULL , [Status] VARCHAR(10) DEFAULT 'new' NOT NULL , CONSTRAINT [pk_Customer_Id] PRIMARY KEY ([Id]) )"
    )]
    [InlineData(
        ConnectionManagerType.Postgres,
        "CREATE TABLE \"Customer\" ( \"Id\" INT GENERATED BY DEFAULT AS IDENTITY (MINVALUE 1 INCREMENT BY 1) , \"Name\" VARCHAR(100) NOT NULL , \"Notes\" VARCHAR(300) NULL , \"Bio\" TEXT NULL , \"Amount\" DECIMAL(18,2) NULL , \"Created\" TIMESTAMP NOT NULL , \"Counter\" BIGINT NOT NULL , \"Status\" VARCHAR(10) DEFAULT 'new' NOT NULL , CONSTRAINT \"pk_Customer_Id\" PRIMARY KEY (\"Id\") )"
    )]
    [InlineData(
        ConnectionManagerType.MySql,
        "CREATE TABLE `Customer` ( `Id` INT AUTO_INCREMENT , `Name` NVARCHAR(100) , `Notes` NVARCHAR(300) , `Bio` TEXT , `Amount` DECIMAL(18,2) , `Created` DATETIME , `Counter` BIGINT , `Status` VARCHAR(10) DEFAULT 'new' , CONSTRAINT `pk_Customer_Id` PRIMARY KEY (`Id`) )"
    )]
    [InlineData(
        ConnectionManagerType.SQLite,
        "CREATE TABLE \"Customer\" ( \"Id\" INTEGER NOT NULL , \"Name\" NVARCHAR(100) NOT NULL , \"Notes\" NVARCHAR(300) , \"Bio\" TEXT , \"Amount\" DECIMAL(18,2) , \"Created\" DATETIME NOT NULL , \"Counter\" INTEGER NOT NULL , \"Status\" VARCHAR(10) DEFAULT 'new' NOT NULL , PRIMARY KEY (\"Id\") )"
    )]
    [InlineData(
        ConnectionManagerType.Access,
        "CREATE TABLE [Customer] ( [Id] INTEGER IDENTITY(1,1) , [Name] VARCHAR(100) , [Notes] LONGTEXT , [Bio] TEXT , [Amount] DECIMAL(18,2) , [Created] DATETIME , [Counter] BIGINT , [Status] VARCHAR(10) DEFAULT 'new' , CONSTRAINT [pk_Customer_Id] PRIMARY KEY ([Id]) )"
    )]
    [InlineData(
        ConnectionManagerType.ClickHouse,
        "CREATE TABLE `Customer` ( `Id` INT NOT NULL , `Name` String NOT NULL , `Notes` Nullable(String) , `Bio` Nullable(TEXT) , `Amount` Nullable(DECIMAL(18,2)) , `Created` DATETIME NOT NULL , `Counter` BIGINT NOT NULL , `Status` String DEFAULT 'new' NOT NULL , PRIMARY KEY (`Id`) ) ENGINE = MergeTree()"
    )]
    public void Sql_CustomerTable_ProducesEngineSpecificDdl(
        ConnectionManagerType engine,
        string expected
    ) =>
        Assert.Equal(
            expected,
            BuildSql(
                engine,
                "Customer",
                CustomerColumns(identity: engine != ConnectionManagerType.ClickHouse)
            )
        );

    // A computed column has no data type of its own on SQL Server: the type is dropped and the
    // expression stands in for it.
    [Fact]
    public void Sql_SqlServerComputedColumn_OmitsTypeAndNullConstraint()
    {
        List<TableColumn> columns =
        [
            new("Qty", "INT", allowNulls: false),
            new("Price", "DECIMAL(18,2)", allowNulls: false),
            new("Total", "DECIMAL(18,2)", allowNulls: false) { ComputedColumn = "Qty * Price" },
        ];

        Assert.Equal(
            "CREATE TABLE [Orders] ( [Qty] INT NOT NULL , [Price] DECIMAL(18,2) NOT NULL , [Total] AS (Qty * Price) )",
            BuildSql(ConnectionManagerType.SqlServer, "Orders", columns)
        );
    }

    // The identity seed and increment are honored by SQL Server and PostgreSQL only.
    [Theory]
    [InlineData(
        ConnectionManagerType.SqlServer,
        "CREATE TABLE [Seeded] ( [Id] INT IDENTITY(10,5) NOT NULL )"
    )]
    [InlineData(
        ConnectionManagerType.Postgres,
        "CREATE TABLE \"Seeded\" ( \"Id\" INT GENERATED BY DEFAULT AS IDENTITY (MINVALUE 10 INCREMENT BY 5) )"
    )]
    public void Sql_IdentityWithSeedAndIncrement_UsesBothValues(
        ConnectionManagerType engine,
        string expected
    )
    {
        List<TableColumn> columns =
        [
            new("Id", "INT", allowNulls: false, isPrimaryKey: false, isIdentity: true)
            {
                IdentitySeed = 10,
                IdentityIncrement = 5,
            },
        ];

        Assert.Equal(expected, BuildSql(engine, "Seeded", columns));
    }

    // The ODBC manager reports the same engine as the native one, so both must emit the same DDL.
    [Fact]
    public void Sql_SqlServerOdbc_ProducesTheSameDdlAsTheNativeManager()
    {
        using var managerCase = TestConnectionManagers.Get("SqlServerOdbc");

        var expected = BuildSql(
            ConnectionManagerType.SqlServer,
            "Customer",
            CustomerColumns(identity: true)
        );

        Assert.Equal(
            expected,
            BuildSql(managerCase.Manager, "Customer", CustomerColumns(identity: true))
        );
    }

    // A custom IConnectionManager that is not a DbConnectionManager supplies no conventions of its
    // own, so CreateTableTask keeps applying the rules of the engine it reports.
    [Fact]
    public void Sql_CustomConnectionManager_UsesTheRulesOfTheEngineItReports()
    {
        var manager = Mock.Of<IConnectionManager>(m =>
            m.ConnectionManagerType == ConnectionManagerType.Postgres
            && m.QB == "\""
            && m.QE == "\""
        );
        List<TableColumn> columns =
        [
            new("Name", "NVARCHAR(100)", allowNulls: false),
            new("Created", "DATETIME", allowNulls: false),
        ];

        Assert.Equal(
            "CREATE TABLE \"Custom\" ( \"Name\" VARCHAR(100) NOT NULL , \"Created\" TIMESTAMP NOT NULL )",
            BuildSql(manager, "Custom", columns)
        );
    }

    // A user's own OdbcConnectionManager (here PostgreSQL over ODBC) reports its engine itself and
    // must keep getting that engine's DDL, as it did when the rules were picked by engine.
    [Fact]
    public void Sql_OdbcSubclassReportingPostgres_UsesPostgresRules()
    {
        using var manager = new CustomOdbcConnectionManager(ConnectionManagerType.Postgres);
        List<TableColumn> columns =
        [
            new("Name", "NVARCHAR(100)", allowNulls: false),
            new("Created", "DATETIME", allowNulls: false),
        ];

        Assert.Equal(
            "CREATE TABLE \"Custom\" ( \"Name\" VARCHAR(100) NOT NULL , \"Created\" TIMESTAMP NOT NULL )",
            BuildSql(manager, "Custom", columns)
        );
    }

    [Fact]
    public void Sql_ManagerSupplyingItsOwnConventions_UsesThemInsteadOfTheEngineRules()
    {
        using var manager = new CustomManagerWithOwnConventions(new EveryColumnIsTextConventions());
        List<TableColumn> columns =
        [
            new("Name", "NVARCHAR(100)", allowNulls: false),
            new("Created", "DATETIME", allowNulls: false),
        ];

        Assert.Equal(
            "CREATE TABLE \"Custom\" ( \"Name\" TEXT NOT NULL , \"Created\" TEXT NOT NULL )",
            BuildSql(manager, "Custom", columns)
        );
    }
}
